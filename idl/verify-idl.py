#!/usr/bin/env python3
"""Verify that published Codama & Anchor IDLs match crates/audren-core byte-for-byte."""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "idl"))

import importlib.util

spec = importlib.util.spec_from_file_location("gen_idl", ROOT / "idl" / "generate-idl.py")
gen = importlib.util.module_from_spec(spec)
assert spec and spec.loader
spec.loader.exec_module(gen)


def fixed_type_size(t: dict, defined: dict) -> int | None:
    k = t["kind"]
    if k == "numberTypeNode":
        return {"u8": 1, "i8": 1, "u16": 2, "i16": 2, "u32": 4, "i32": 4, "u64": 8, "i64": 8}[t["format"]]
    if k == "booleanTypeNode":
        return 1
    if k == "publicKeyTypeNode":
        return 32
    if k == "fixedSizeTypeNode":
        return t["size"]
    if k == "arrayTypeNode":
        item_sz = fixed_type_size(t["item"], defined)
        return None if item_sz is None else item_sz * t["count"]["value"]
    if k == "definedTypeLinkNode":
        dt = defined[t["name"]]["type"]
        if dt["kind"] == "enumTypeNode":
            return fixed_type_size(dt["size"], defined)
        return sum(fixed_type_size(f["type"], defined) for f in dt["fields"])
    if k == "bytesTypeNode":
        return None
    raise ValueError(f"Unknown type kind: {k}")


def main() -> None:
    core = gen.parse_core_constants()
    expected_codama = gen.build_audren_codama(core)
    expected_anchor = gen.build_audren_anchor(core, expected_codama)
    expected_mock = gen.build_mock_router_codama()

    # 1. Byte-for-byte freshness check
    checks = [
        (ROOT / "idl" / "audren.codama.json", expected_codama),
        (ROOT / "idl" / "audren.anchor.json", expected_anchor),
        (ROOT / "idl" / "audren-mock-router.codama.json", expected_mock),
        (ROOT / "packages" / "sdk" / "idl" / "audren.codama.json", expected_codama),
        (ROOT / "packages" / "sdk" / "idl" / "audren.anchor.json", expected_anchor),
    ]
    for path, exp in checks:
        actual = json.loads(path.read_text())
        assert actual == exp, f"Stale or drifted IDL at {path}; run python3 idl/generate-idl.py"

    # Also verify packages/sdk/src/idl.ts stays synced
    sdk_ts_expected = (
        "// AUTO-GENERATED by idl/generate-idl.py from crates/audren-core — DO NOT EDIT BY HAND.\n"
        "// Re-run `python3 idl/generate-idl.py && python3 idl/verify-idl.py` after any protocol change.\n\n"
        f"export const AUDREN_CODAMA_IDL = {json.dumps(expected_codama, indent=2)} as const;\n\n"
        f"export const AUDREN_ANCHOR_IDL = {json.dumps(expected_anchor, indent=2)} as const;\n"
    )
    sdk_ts_path = ROOT / "packages" / "sdk" / "src" / "idl.ts"
    assert sdk_ts_path.read_text() == sdk_ts_expected, (
        f"Stale or drifted TS IDL at {sdk_ts_path}; run python3 idl/generate-idl.py"
    )

    prog = expected_codama["program"]
    defined = {dt["name"]: dt for dt in prog["definedTypes"]}

    # 2. Verify all 13 instruction tags 0..=12
    ix_tags = sorted(ix["discriminators"][0]["constant"]["value"]["number"] for ix in prog["instructions"])
    assert ix_tags == list(range(len(core["tags"]))), f"Instruction tag gap: {ix_tags}"
    assert len(expected_anchor["instructions"]) == len(core["tags"])

    # 3. Verify all 33 error codes 1..=33
    codama_errs = [(e["code"], e["name"].lower()) for e in prog["errors"]]
    core_errs = [(code, name.lower()) for name, code in core["errors"]]
    assert codama_errs == core_errs, "Codama errors do not match AudrenError"
    anchor_errs = [(e["code"], e["name"].lower()) for e in expected_anchor["errors"]]
    assert anchor_errs == core_errs, "Anchor errors do not match AudrenError"

    # 4. Verify every fixed-size account's field sum matches crates/audren-core/src/layout.rs
    expected_sizes = {
        "poolState": core["lengths"]["POOL_STATE_LEN"],
        "epochPage": core["lengths"]["PAGE_LEN"],
        "appendLaneState": core["lengths"]["LANE_STATE_LEN"],
        "solVaultSentinel": core["lengths"]["SENTINEL_ACCOUNT_LEN"],
        "pageRentSentinel": core["lengths"]["SENTINEL_ACCOUNT_LEN"],
        "nullifierPda": 0,
    }
    for acc in prog["accounts"]:
        name = acc["name"]
        if name in expected_sizes:
            computed = sum(fixed_type_size(f["type"], defined) for f in acc["data"]["fields"])
            assert computed == expected_sizes[name], (
                f"Account {name} field sum {computed} != layout.rs {expected_sizes[name]}"
            )
            assert acc["size"] == expected_sizes[name]

    # 5. Verify all 10 PDA constant seeds match crates/audren-core/src/lib.rs
    pda_names = {p["name"] for p in prog["pdas"]}
    pda_prefixes = {p["seeds"][0]["value"]["data"] for p in prog["pdas"]}
    core_seeds = set(core["seeds"].values())
    assert pda_prefixes == core_seeds, f"PDA seeds mismatch: {pda_prefixes ^ core_seeds}"

    # 6. Verify instruction pdaValueNode links reference valid PDAs and have no duplicate Explorer rows
    seen_acc_to_pda: dict[str, str] = {}
    seen_pda_to_acc: dict[str, str] = {}
    for ix in prog["instructions"]:
        for acc in ix["accounts"]:
            dv = acc.get("defaultValue")
            if dv and dv.get("kind") == "pdaValueNode":
                target = dv["pda"]["name"]
                assert target in pda_names, f"Unknown pdaLinkNode target {target} in {ix['name']}.{acc['name']}"
                prev_pda = seen_acc_to_pda.setdefault(acc["name"], target)
                assert prev_pda == target, f"Account name {acc['name']} maps to conflicting PDAs {prev_pda} vs {target}"
                prev_acc = seen_pda_to_acc.setdefault(target, acc["name"])
                assert prev_acc == acc["name"], (
                    f"PDA {target} referenced by multiple account names ({prev_acc}, {acc['name']}); "
                    "would duplicate rows in Solana Explorer BaseIdlPdas"
                )

    # 7. Verify canonical Program Metadata security.json and version alignment
    prog_version = gen.PROGRAM_VERSION
    sec_path = ROOT / "idl" / "security.json"
    sec = json.loads(sec_path.read_text())
    for required_key in ("name", "project_url", "contacts", "policy", "source_code", "version", "source_release"):
        assert sec.get(required_key), f"Missing required security.json key: {required_key}"
    assert "email:security@audren.xyz" in sec["contacts"], "security.json missing email:security@audren.xyz"
    assert sec["version"] == prog_version, (
        f"security.json version {sec['version']} != program/Cargo.toml {prog_version}; run python3 idl/generate-idl.py"
    )
    assert sec["source_release"] == f"v{prog_version}", (
        f"security.json source_release {sec['source_release']} != v{prog_version}; run python3 idl/generate-idl.py"
    )

    # 8. Verify protocol version parity across Rust protocol crates and @audren/sdk
    root_ws_ver = gen.read_toml_value(ROOT / "Cargo.toml", "workspace.package", "version")
    assert root_ws_ver == prog_version, f"Cargo.toml [workspace.package].version {root_ws_ver} != program/Cargo.toml {prog_version}"
    for rel_manifest in ("crates/audren-core/Cargo.toml", "crates/client/Cargo.toml", "tests/mock-router/Cargo.toml"):
        ver = gen.read_cargo_version(ROOT / rel_manifest)
        assert ver == prog_version, f"{rel_manifest} version {ver} != program/Cargo.toml {prog_version}"
    sdk_pkg = json.loads((ROOT / "packages" / "sdk" / "package.json").read_text())
    assert sdk_pkg["version"] == prog_version, (
        f"packages/sdk/package.json version {sdk_pkg['version']} != program/Cargo.toml {prog_version}"
    )

    # 9. Verify every Solana program crate embeds `.security.txt` bound to CARGO_PKG_VERSION
    for rel_src in ("program/src/lib.rs", "tests/mock-router/src/lib.rs"):
        src = (ROOT / rel_src).read_text()
        assert 'link_section = ".security.txt"' in src, f"{rel_src} missing .security.txt link_section"
        assert "email:security@audren.xyz" in src, f"{rel_src} .security.txt missing email:security@audren.xyz"
        assert 'env!("CARGO_PKG_VERSION")' in src, f"{rel_src} .security.txt must bind source_release to CARGO_PKG_VERSION"

    # 10. Verify Verified Build manifest metadata and sBPFv3 toolchain pin parity
    build_sbf = (ROOT / "scripts" / "build-sbf.py").read_text()
    upgrade_sh = (ROOT / "scripts" / "upgrade-program.sh").read_text()
    builder_ver = re.search(r'^BUILDER_VERSION\s*=\s*"([^"]+)"', build_sbf, re.M).group(1)
    tools_ver = re.search(r'^TOOLS_VERSION\s*=\s*"([^"]+)"', build_sbf, re.M).group(1)
    sbf_arch = re.search(r'^ARCH\s*=\s*"([^"]+)"', build_sbf, re.M).group(1)

    for rel_manifest, expected_lib in (
        ("program/Cargo.toml", "audren"),
        ("tests/mock-router/Cargo.toml", "audren_mock_router"),
    ):
        manifest_path = ROOT / rel_manifest
        lib_name = gen.read_toml_value(manifest_path, "lib", "name")
        assert lib_name == expected_lib, (
            f"{rel_manifest} must declare explicit [lib] name = \"{expected_lib}\" for solana-verify (got {lib_name})"
        )
        cli_solana = gen.read_toml_value(manifest_path, "workspace.metadata.cli", "solana")
        assert cli_solana == builder_ver, (
            f"{rel_manifest} [workspace.metadata.cli] solana ({cli_solana}) must match build-sbf.py BUILDER_VERSION ({builder_ver})"
        )

    sh_agave = re.search(r'^AGAVE_VERSION="([^"]+)"', upgrade_sh, re.M).group(1)
    sh_tools = re.search(r'^TOOLS_VERSION="([^"]+)"', upgrade_sh, re.M).group(1)
    sh_arch = re.search(r'^SBF_ARCH="([^"]+)"', upgrade_sh, re.M).group(1)
    sh_img = re.search(r'^VERIFY_BASE_IMAGE="([^"]+)"', upgrade_sh, re.M).group(1)
    assert sh_agave == builder_ver, f"upgrade-program.sh AGAVE_VERSION ({sh_agave}) != build-sbf.py ({builder_ver})"
    assert sh_tools == tools_ver, f"upgrade-program.sh TOOLS_VERSION ({sh_tools}) != build-sbf.py ({tools_ver})"
    assert sh_arch == sbf_arch, f"upgrade-program.sh SBF_ARCH ({sh_arch}) != build-sbf.py ({sbf_arch})"
    assert "@sha256:" in sh_img, f"upgrade-program.sh VERIFY_BASE_IMAGE must be digest-pinned: {sh_img}"

    print(
        f"verify-idl: ok (v{prog_version}, {len(ix_tags)} instructions, {len(expected_sizes)} fixed accounts + ProofBuffer, "
        f"{len(pda_prefixes)} PDAs ({len(seen_pda_to_acc)} linked in ixs), {len(core_errs)} errors, "
        f"security.json, .security.txt, and Agave {builder_ver}/{tools_ver}/sBPF{sbf_arch} verify pins matched)"
    )


if __name__ == "__main__":
    main()

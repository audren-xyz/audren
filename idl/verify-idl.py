def fixed_type_size(t: dict, defined: dict) -> int | None:
    k = t["kind"]
    if k == "numberTypeNode":
        return {"u8": 1, "i8": 1, "u16": 2, "i16": 2, "u32": 4, "i32": 4, "u64": 8, "i64": 8}[t["format"]]
    if k == "booleanTypeNode":
        return 1
    if k == "publicKeyTypeNode":
        return 32
    if k == "fixedSizeTypeNode":
        return t["size"]
    if k == "arrayTypeNode":
        item_sz = fixed_type_size(t["item"], defined)
        return None if item_sz is None else item_sz * t["count"]["value"]
    if k == "definedTypeLinkNode":
        dt = defined[t["name"]]["type"]
        if dt["kind"] == "enumTypeNode":
            return fixed_type_size(dt["size"], defined)
        return sum(fixed_type_size(f["type"], defined) for f in dt["fields"])
    if k == "bytesTypeNode":
        return None
    raise ValueError(f"Unknown type kind: {k}")


def parse_ts_string_array(text: str, symbol: str) -> list[str]:
    m = re.search(rf"{symbol}[^=]*=\s*&?\[([^\]]+)\]", text, re.S)
    assert m, f"Missing {symbol} array"
    return re.findall(r"['\"]([^'\"]+)['\"]", m.group(1))


def parse_ts_const_str(text: str, key: str) -> str:
    m = re.search(rf"\b{key}:\s*['\"]([^'\"]+)['\"]", text)
    assert m, f"Missing string property '{key}' in apps/web/lib/protocol.ts"
    return m.group(1)


def main() -> None:
    core = gen.parse_core_constants()
    expected_codama = gen.build_audren_codama(core)
    expected_anchor = gen.build_audren_anchor(core, expected_codama)
    expected_mock = gen.build_mock_router_codama()

    # 1. Byte-for-byte freshness check for all generated IDLs
    checks = [
        (ROOT / "idl" / "audren.codama.json", expected_codama),
        (ROOT / "idl" / "audren.anchor.json", expected_anchor),
        (ROOT / "idl" / "audren-mock-router.codama.json", expected_mock),
        (ROOT / "packages" / "sdk" / "idl" / "audren.codama.json", expected_codama),
        (ROOT / "packages" / "sdk" / "idl" / "audren.anchor.json", expected_anchor),
    ]
    for path, exp in checks:
        actual = json.loads(path.read_text())
        assert actual == exp, f"Stale or drifted IDL at {path}; run python3 idl/generate-idl.py"

    sdk_ts_expected = (
        "// AUTO-GENERATED by idl/generate-idl.py from crates/audren-core — DO NOT EDIT BY HAND.\n"
        "// Re-run `python3 idl/generate-idl.py && python3 idl/verify-idl.py` after any protocol change.\n\n"
        f"export const AUDREN_CODAMA_IDL = {json.dumps(expected_codama, indent=2)} as const;\n\n"
        f"export const AUDREN_ANCHOR_IDL = {json.dumps(expected_anchor, indent=2)} as const;\n"
    )
    sdk_ts_path = ROOT / "packages" / "sdk" / "src" / "idl.ts"
    assert sdk_ts_path.read_text() == sdk_ts_expected, (
        f"Stale or drifted TS IDL at {sdk_ts_path}; run python3 idl/generate-idl.py"
    )

    prog = expected_codama["program"]
    defined = {dt["name"]: dt for dt in prog["definedTypes"]}

    # 2. Verify all 9 instruction tags 0..=8
    ix_tags = sorted(ix["discriminators"][0]["constant"]["value"]["number"] for ix in prog["instructions"])
    assert ix_tags == list(range(len(core["tags"]))), f"Instruction tag gap: {ix_tags}"
    assert len(ix_tags) == 9, f"Expected 9 instructions, found {len(ix_tags)}"
    assert len(expected_anchor["instructions"]) == len(core["tags"])

    # 3. Verify all 33 error codes 6000..=6032
    codama_errs = [(e["code"], e["name"].lower()) for e in prog["errors"]]
    core_errs = [(code, name.lower()) for name, code in core["errors"]]
    assert codama_errs == core_errs, "Codama errors do not match AudrenError"
    anchor_errs = [(e["code"], e["name"].lower()) for e in expected_anchor["errors"]]
    assert anchor_errs == core_errs, "Anchor errors do not match AudrenError"

    # 4. Verify every fixed-size account's field sum matches crates/audren-core/src/layout.rs
    expected_sizes = {
        "poolState": core["lengths"]["POOL_STATE_LEN"],
        "laneRentVault": core["lengths"]["SENTINEL_LEN"],
        "laneTreeState": core["lengths"]["LANE_STATE_LEN"],
        "subtreePage": core["lengths"]["SUBTREE_PAGE_LEN"],
        "subtreeRootPage": core["lengths"]["SUBROOT_PAGE_LEN"],
        "memoPage": core["lengths"]["MEMO_PAGE_LEN"],
        "nullifierPage": core["lengths"]["NF_PAGE_LEN"],
        "rootCheckpoint": core["lengths"]["CKPT_LEN"],
    }
    actual_account_names = {acc["name"] for acc in prog["accounts"]}
    assert actual_account_names == set(expected_sizes.keys()), (
        f"IDL accounts {actual_account_names} != expected {set(expected_sizes.keys())}"
    )
    for acc in prog["accounts"]:
        name = acc["name"]
        computed = sum(fixed_type_size(f["type"], defined) for f in acc["data"]["fields"])
        assert computed == expected_sizes[name], (
            f"Account {name} field sum {computed} != layout.rs {expected_sizes[name]}"
        )
        assert acc["size"] == expected_sizes[name]

    # 5. Verify all 13 PDA constant seeds match crates/audren-core/src/lib.rs
    pda_names = {p["name"] for p in prog["pdas"]}
    pda_prefixes = {p["seeds"][0]["value"]["data"] for p in prog["pdas"]}
    core_seeds = set(core["seeds"].values())
    assert pda_prefixes == core_seeds, f"PDA seeds mismatch: {pda_prefixes ^ core_seeds}"
    assert len(pda_prefixes) == 13, f"Expected 13 PDA seeds, found {len(pda_prefixes)}"

    # 6. Verify instruction pdaValueNode links reference valid PDAs and have no duplicate Explorer rows
    seen_acc_to_pda: dict[str, str] = {}
    seen_pda_to_acc: dict[str, str] = {}
    for ix in prog["instructions"]:
        for acc in ix["accounts"]:
            dv = acc.get("defaultValue")
            if dv and dv.get("kind") == "pdaValueNode":
                target = dv["pda"]["name"]
                assert target in pda_names, f"Unknown pdaLinkNode target {target} in {ix['name']}.{acc['name']}"
                prev_pda = seen_acc_to_pda.setdefault(acc["name"], target)
                assert prev_pda == target, f"Account name {acc['name']} maps to conflicting PDAs {prev_pda} vs {target}"
                prev_acc = seen_pda_to_acc.setdefault(target, acc["name"])
                assert prev_acc == acc["name"], (
                    f"PDA {target} referenced by multiple account names ({prev_acc}, {acc['name']}); "
                    "would duplicate rows in Solana Explorer BaseIdlPdas"
                )

    # 7. Verify canonical Program Metadata security.json and version alignment
    prog_version = gen.PROGRAM_VERSION
    sec_path = ROOT / "idl" / "security.json"
    sec = json.loads(sec_path.read_text())
    for required_key in ("name", "project_url", "contacts", "policy", "source_code", "version", "source_release"):
        assert sec.get(required_key), f"Missing required security.json key: {required_key}"
    assert "email:security@audren.xyz" in sec["contacts"], "security.json missing email:security@audren.xyz"
    assert sec["version"] == prog_version, (
        f"security.json version {sec['version']} != program/Cargo.toml {prog_version}; run python3 idl/generate-idl.py"
    )
    assert sec["source_release"] == f"v{prog_version}", (
        f"security.json source_release {sec['source_release']} != v{prog_version}; run python3 idl/generate-idl.py"
    )

    # 8. Verify unified release version parity across all 12 Rust, TypeScript & Kotlin manifests
    root_ws_ver = gen.read_toml_value(ROOT / "Cargo.toml", "workspace.package", "version")
    assert root_ws_ver == prog_version, f"Cargo.toml [workspace.package].version {root_ws_ver} != program/Cargo.toml {prog_version}"
    for rel_manifest in (
        "crates/audren-core/Cargo.toml",
        "crates/audren-circuits/Cargo.toml",
        "crates/client/Cargo.toml",
        "crates/audren-ffi/Cargo.toml",
        "tests/mock-router/Cargo.toml",
        "tests/mock-hook/Cargo.toml",
    ):
        txt = (ROOT / rel_manifest).read_text()
        if "version.workspace = true" in txt:
            continue
        ver = gen.read_cargo_version(ROOT / rel_manifest)
        assert ver == prog_version, f"{rel_manifest} version {ver} != program/Cargo.toml {prog_version}"
    for rel_pkg in ("packages/sdk/package.json", "apps/relay/package.json", "apps/web/package.json"):
        pkg = json.loads((ROOT / rel_pkg).read_text())
        assert pkg["version"] == prog_version, (
            f"{rel_pkg} version {pkg['version']} != program/Cargo.toml {prog_version}"
        )
    kotlin_gradle = (ROOT / "packages" / "kotlin" / "build.gradle.kts").read_text()
    km = re.search(r'^version\s*=\s*"([^"]+)"', kotlin_gradle, re.M)
    assert km and km.group(1) == prog_version, (
        f"packages/kotlin/build.gradle.kts version ({km.group(1) if km else None}) != program/Cargo.toml {prog_version}"
    )

    # 9. Verify every Solana program crate embeds `.security.txt` bound to CARGO_PKG_VERSION
    for rel_src in ("program/src/lib.rs", "tests/mock-router/src/lib.rs"):
        src = (ROOT / rel_src).read_text()
        assert 'link_section = ".security.txt"' in src, f"{rel_src} missing .security.txt link_section"
        assert "email:security@audren.xyz" in src, f"{rel_src} .security.txt missing email:security@audren.xyz"
        assert 'env!("CARGO_PKG_VERSION")' in src, f"{rel_src} .security.txt must bind source_release to CARGO_PKG_VERSION"

    # 10. Verify Verified Build manifest metadata and sBPFv3 toolchain pin parity
    build_sbf = (ROOT / "scripts" / "build-sbf.py").read_text()
    upgrade_sh = (ROOT / "scripts" / "upgrade-program.sh").read_text()
    builder_ver = re.search(r'^BUILDER_VERSION\s*=\s*"([^"]+)"', build_sbf, re.M).group(1)
    tools_ver = re.search(r'^TOOLS_VERSION\s*=\s*"([^"]+)"', build_sbf, re.M).group(1)
    sbf_arch = re.search(r'^ARCH\s*=\s*"([^"]+)"', build_sbf, re.M).group(1)

    for rel_manifest, expected_lib in (
        ("program/Cargo.toml", "audren"),
        ("tests/mock-router/Cargo.toml", "audren_mock_router"),
        ("tests/mock-hook/Cargo.toml", "audren_mock_hook"),
    ):
        manifest_path = ROOT / rel_manifest
        lib_name = gen.read_toml_value(manifest_path, "lib", "name")
        assert lib_name == expected_lib, (
            f"{rel_manifest} must declare explicit [lib] name = \"{expected_lib}\" (got {lib_name})"
        )
        cli_solana = gen.read_toml_value(manifest_path, "workspace.metadata.cli", "solana")
        assert cli_solana == builder_ver, (
            f"{rel_manifest} [workspace.metadata.cli] solana ({cli_solana}) must match build-sbf.py BUILDER_VERSION ({builder_ver})"
        )

    sh_agave = re.search(r'^AGAVE_VERSION="([^"]+)"', upgrade_sh, re.M).group(1)
    sh_tools = re.search(r'^TOOLS_VERSION="([^"]+)"', upgrade_sh, re.M).group(1)
    sh_arch = re.search(r'^SBF_ARCH="([^"]+)"', upgrade_sh, re.M).group(1)
    sh_img = re.search(r'^VERIFY_BASE_IMAGE="([^"]+)"', upgrade_sh, re.M).group(1)
    assert sh_agave == builder_ver, f"upgrade-program.sh AGAVE_VERSION ({sh_agave}) != build-sbf.py ({builder_ver})"
    assert sh_tools == tools_ver, f"upgrade-program.sh TOOLS_VERSION ({sh_tools}) != build-sbf.py ({tools_ver})"
    assert sh_arch == sbf_arch, f"upgrade-program.sh SBF_ARCH ({sh_arch}) != build-sbf.py ({sbf_arch})"
    assert "@sha256:" in sh_img, f"upgrade-program.sh VERIFY_BASE_IMAGE must be digest-pinned: {sh_img}"

    rust_channel = gen.read_toml_value(ROOT / "rust-toolchain.toml", "toolchain", "channel")
    host_ver = re.search(r'^HOST_VERSION\s*=\s*"([^"]+)"', build_sbf, re.M).group(1)
    assert host_ver == rust_channel, (
        f"scripts/build-sbf.py HOST_VERSION ({host_ver}) != rust-toolchain.toml ({rust_channel})"
    )
    ci_yml = (ROOT / ".github" / "workflows" / "ci.yml").read_text()
    ci_rust_all = re.findall(r"toolchain:\s*'([^']+)'", ci_yml)
    assert ci_rust_all and all(t == rust_channel for t in ci_rust_all), (
        f".github/workflows/ci.yml Rust toolchains ({ci_rust_all}) != rust-toolchain.toml ({rust_channel})"
    )
    assert sh_img in ci_yml, (
        f".github/workflows/ci.yml Docker verifiable-build image drifted from scripts/upgrade-program.sh ({sh_img})"
    )
    assert f"--arch {sbf_arch}" in ci_yml and f"--tools-version {tools_ver}" in ci_yml, (
        f".github/workflows/ci.yml sBPF arch/tools pins drifted from scripts/build-sbf.py ({sbf_arch}, {tools_ver})"
    )

    # 11. Verify cross-layer JUPITER_CPI_EXCLUDED_DEXES parity across Rust, SDK, Relayer, and Web Worker
    rust_router = (ROOT / "crates" / "client" / "src" / "router.rs").read_text()
    rust_dexes = parse_ts_string_array(rust_router, "JUPITER_CPI_EXCLUDED_DEXES")
    sdk_dexes = parse_ts_string_array((ROOT / "packages" / "sdk" / "src" / "swap.ts").read_text(), "JUPITER_CPI_EXCLUDED_DEXES")
    relay_dexes = parse_ts_string_array(
        (ROOT / "apps" / "relay" / "src" / "aggregators" / "jupiter.ts").read_text(),
        "JUPITER_CPI_EXCLUDED_DEXES",
    )
    web_dexes = parse_ts_string_array((ROOT / "apps" / "web" / "worker" / "index.ts").read_text(), "JUPITER_CPI_EXCLUDED_DEXES")
    assert rust_dexes == sdk_dexes == relay_dexes == web_dexes, (
        "JUPITER_CPI_EXCLUDED_DEXES drifted across layers:\n"
        f"  rust:  {rust_dexes}\n  sdk:   {sdk_dexes}\n  relay: {relay_dexes}\n  web:   {web_dexes}"
    )

    # 12. Verify SDK & Relayer wire constants match crates/audren-core
    sdk_consts = (ROOT / "packages" / "sdk" / "src" / "constants.ts").read_text()
    assert f"AUDREN_PROGRAM_ID = '{CANONICAL_PROGRAM_ID}'" in sdk_consts, "SDK AUDREN_PROGRAM_ID mismatch"
    for seed_val in core_seeds:
        assert f"'{seed_val}'" in sdk_consts, f"SDK constants.ts missing PDA seed '{seed_val}'"
    for len_key in (
        "POOL_STATE_LEN",
        "SENTINEL_LEN",
        "LANE_STATE_LEN",
        "SUBTREE_PAGE_LEN",
        "SUBROOT_PAGE_LEN",
        "MEMO_PAGE_LEN",
        "NF_PAGE_LEN",
        "CKPT_LEN",
    ):
        m = re.search(rf"export const {len_key} = ([0-9_]+);", sdk_consts)
        assert m and int(m.group(1).replace("_", "")) == core["lengths"][len_key], (
            f"SDK constants.ts {len_key} drifted from crates/audren-core"
        )
    for tag_name, tag_val in core["tags"].items():
        m = re.search(rf"export const {tag_name} = (0x[0-9a-fA-F]+|\d+);", sdk_consts)
        assert m and int(m.group(1), 0) == tag_val, (
            f"SDK constants.ts {tag_name} drifted from crates/audren-core ({tag_val})"
        )
    for magic_name, magic_val in core["magics"].items():
        assert f"export const {magic_name} = '{magic_val}';" in sdk_consts, (
            f"SDK constants.ts {magic_name} drifted from crates/audren-core ('{magic_val}')"
        )
    for err_name, err_code in core["errors"]:
        assert re.search(rf"\b{err_code}:\s*'{err_name}'", sdk_consts), (
            f"SDK AUDREN_ERRORS[{err_code}] = '{err_name}' missing or drifted"
        )

    core_ix_src = (
        (ROOT / "crates" / "audren-core" / "src" / "instruction.rs").read_text()
        + "\n"
        + (ROOT / "crates" / "audren-core" / "src" / "layout.rs").read_text()
        + "\n"
        + (ROOT / "crates" / "audren-core" / "src" / "lib.rs").read_text()
    )
    for dom_name, dom_val in re.findall(r"pub const (DOMAIN_[A-Z0-9_]+):\s*u64\s*=\s*(\d+);", core_ix_src):
        assert f"export const {dom_name} = {dom_val}n;" in sdk_consts, (
            f"SDK constants.ts {dom_name} drifted from crates/audren-core ({dom_val}n)"
        )
    for ctx_name, ctx_val in re.findall(r'pub const ((?:ASSET_ID|CTX)_DOMAIN[A-Z0-9_]*):\s*&\[u8\]\s*=\s*b"([^"]+)";', core_ix_src):
        assert f"export const {ctx_name} = '{ctx_val}';" in sdk_consts, (
            f"SDK constants.ts {ctx_name} drifted from crates/audren-core ('{ctx_val}')"
        )

    def eval_int_expr(expr: str) -> int:
        expr = expr.strip().replace("_", "")
        if "<<" in expr:
            lhs, rhs = expr.split("<<", 1)
            return int(lhs.strip(), 0) << int(rhs.strip(), 0)
        return int(expr, 0)

    def parse_const_val(src: str, sym: str, lang: str) -> int:
        pat = (
            rf"pub const {sym}:\s*(?:u8|usize)\s*=\s*([^;]+);"
            if lang == "rust"
            else rf"export const {sym}\s*=\s*([^;\n]+)"
        )
        m = re.search(pat, src)
        assert m, f"Missing constant {sym} ({lang})"
        return eval_int_expr(m.group(1))

    for sym in (
        "DEPOSIT_FLAG_FEE_FROM_AMOUNT",
        "WITHDRAW_FLAG_UNWRAP_WSOL",
        "EXEC_FLAG_FEE_ON_OUTPUT",
        "GROTH16_PROOF_LEN",
        "MEMO_CT_LEN",
    ):
        rv = parse_const_val(core_ix_src, sym, "rust")
        sv = parse_const_val(sdk_consts, sym, "ts")
        assert rv == sv, f"Wire constant {sym} drifted: rust={rv}, sdk={sv}"

    relay_audren = (ROOT / "apps" / "relay" / "src" / "solana" / "audren.ts").read_text()
    assert "@audren/sdk" in relay_audren, "apps/relay/src/solana/audren.ts must import canonical helpers from @audren/sdk"

    # 13. Verify WASM prover & canonical ceremony ProvingKey parity across Rust, SDK, Web, and program VK
    sdk_wasm = ROOT / "packages" / "sdk" / "wasm" / "audren_circuits.wasm"
    web_wasm = ROOT / "apps" / "web" / "public" / "wasm" / "audren_circuits.wasm"
    assert sdk_wasm.is_file() and web_wasm.is_file(), "Missing audren_circuits.wasm in packages/sdk/wasm or apps/web/public/wasm"
    assert sdk_wasm.read_bytes() == web_wasm.read_bytes(), (
        "apps/web/public/wasm/audren_circuits.wasm drifted from packages/sdk/wasm/audren_circuits.wasm"
    )
    rust_pk = ROOT / "crates" / "audren-circuits" / "params" / "audren_joinsplit.pk"
    sdk_pk = ROOT / "packages" / "sdk" / "wasm" / "audren_joinsplit.pk"
    web_pk = ROOT / "apps" / "web" / "public" / "wasm" / "audren_joinsplit.pk"
    for p in (rust_pk, sdk_pk, web_pk):
        assert p.is_file(), f"Missing canonical ceremony proving key: {p.relative_to(ROOT)}"
    pk_bytes = rust_pk.read_bytes()
    assert sdk_pk.read_bytes() == pk_bytes, "packages/sdk/wasm/audren_joinsplit.pk drifted from Rust ceremony PK"
    assert web_pk.read_bytes() == pk_bytes, "apps/web/public/wasm/audren_joinsplit.pk drifted from Rust ceremony PK"
    pk_sha256 = hashlib.sha256(pk_bytes).hexdigest()
    vk_gen_path = ROOT / "program" / "src" / "vk_generated.rs"
    vk_gen_bytes = vk_gen_path.read_bytes()
    vk_gen = vk_gen_bytes.decode("utf-8")
    vk_gen_sha256 = hashlib.sha256(vk_gen_bytes).hexdigest()
    assert pk_sha256 in vk_gen, "program/src/vk_generated.rs PK_COMPRESSED_SHA256 drifted from audren_joinsplit.pk"
    circuits_lib = (ROOT / "crates" / "audren-circuits" / "src" / "lib.rs").read_text(encoding="utf-8")
    assert pk_sha256 in circuits_lib, "crates/audren-circuits/src/lib.rs CANONICAL_PK_SHA256 drifted"
    assert parse_const_val(circuits_lib, "CANONICAL_PK_BYTES", "rust") == len(pk_bytes), (
        "crates/audren-circuits/src/lib.rs CANONICAL_PK_BYTES drifted from audren_joinsplit.pk"
    )
    assert pk_sha256 in sdk_consts, "packages/sdk/src/constants.ts CANONICAL_PK_SHA256 drifted"
    assert parse_const_val(sdk_consts, "CANONICAL_PK_BYTES", "ts") == len(pk_bytes), (
        "packages/sdk/src/constants.ts CANONICAL_PK_BYTES drifted from audren_joinsplit.pk"
    )
    transcript = json.loads((ROOT / "ceremony" / "transcript.json").read_text(encoding="utf-8"))
    assert transcript["final_artifacts"]["proving_key_sha256"] == pk_sha256, (
        "ceremony/transcript.json proving_key_sha256 drifted"
    )
    assert transcript["final_artifacts"]["proving_key_bytes"] == len(pk_bytes), (
        "ceremony/transcript.json proving_key_bytes drifted"
    )
